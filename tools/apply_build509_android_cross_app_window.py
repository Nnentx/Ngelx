#!/usr/bin/env python3
"""Build509: explicitly opt-in native floating call, only for valid background calls.

Runs after Build507 source generation. The source tree's baseline Flutter call
widget is generated by older QA steps; edit that generated widget, never the
live Build484 app. No native permissions are silently granted.
"""
from pathlib import Path

MAIN=Path("app/lib/main.dart")
MODEL=Path("app/lib/build445_inbox_model.dart")
MARK="// Build509: explicitly approved cross-app floating call"

def once(s,old,new,label):
    n=s.count(old)
    if n!=1:raise RuntimeError(f"Build509 {label}: expected one marker, got {n}")
    return s.replace(old,new,1)

def main_transform(src):
    if MARK in src:return src
    src=once(src,"part 'build445_inbox_model.dart';",
      "part 'build445_inbox_model.dart';\npart 'build509_floating_call.dart';",
      "new Flutter part")
    src=once(src,"Future<void> ngelxArkaPlanAramayiTemizle(String roomName)async{",
      "Future<void> ngelxArkaPlanAramayiTemizle(String roomName)async{\n  unawaited(Ngelx509FloatingCallBridge.hide());",
      "remove system window on call cleanup")
    begin=src.index("class _NgelXAramaPageState")
    end=src.index("class GrupBilgiPage",begin)
    head,body,tail=src[:begin],src[begin:end],src[end:]
    body=once(body,
      "  Future<void> _aramaEkraniniKucult()async{",
      """  // Build509: explicitly approved cross-app floating call.
  Future<void> _requestFloating509()async{
    await Ngelx509FloatingCallBridge.requestPermission();
    if(mounted)ScaffoldMessenger.of(context).showSnackBar(const SnackBar(
      content:Text('İzin verdiysen görüşmeyi küçült. Diğer uygulamalarda küçük pencere açılacak.')));
  }
  Future<void> _aramaEkraniniKucult()async{""",
      "user-initiated settings action")
    body=once(body,
      "        baslangic:aramaBaslangic,\n      );",
      """        baslangic:aramaBaslangic,
      );
      unawaited(Ngelx509FloatingCallBridge.showIfAllowed(widget.roomName));""",
      "overlay must only show after background room is saved")
    body=once(body,
      """              const SizedBox(width:5),
              Expanded(child:Text(
                yenidenBaglaniyor?""",
      """              IconButton(
                tooltip:'Diğer uygulamaların üzerinde göster',
                onPressed:()=>unawaited(_requestFloating509()),
                icon:const Icon(Icons.picture_in_picture_alt_rounded,color:Colors.white,size:23),
              ),
              const SizedBox(width:5),
              Expanded(child:Text(
                yenidenBaglaniyor?""",
      "permission activation control in call header")
    return head+body+tail

def model_transform(src):
    if "Ngelx509FloatingCallBridge.install();" in src:return src
    start=src.index("class _Ngelx445CallOverlayState")
    end=src.index("class Ngelx445InboxCallBanner",start)
    a,body,b=src[:start],src[start:end],src[end:]
    body=once(body,"  @override void initState(){super.initState();",
      "  @override void initState(){super.initState();Ngelx509FloatingCallBridge.install();",
      "receive safe native actions from service")
    return a+body+b

def apply(file,transform):
    src=file.read_text(encoding="utf-8")
    out=transform(src)
    if out!=src:file.write_text(out,encoding="utf-8")

if __name__=="__main__":
    apply(MAIN,main_transform)
    apply(MODEL,model_transform)
    print("Build509: explicit Android permission, call-scoped native overlay and cleanup")
