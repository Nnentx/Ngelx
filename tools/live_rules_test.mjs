import {assertSucceeds,assertFails} from '@firebase/rules-unit-testing';
import {doc,collection,getDoc,getDocs,setDoc,updateDoc,deleteDoc,serverTimestamp} from 'firebase/firestore';

export async function testLiveRules(env) {
  await env.withSecurityRulesDisabled(async ctx=>{
    const db=ctx.firestore();
    await setDoc(doc(db,'live_streams/live_rules'),{ownerId:'liveHost',guestUid:'liveGuest',active:true,pk:{hostScore:0,guestScore:0}});
    await setDoc(doc(db,'live_streams/live_closed'),{ownerId:'liveHost',active:false});
    await setDoc(doc(db,'wallets/liveViewer'),{coins:500});
    await setDoc(doc(db,'wallets/liveGuest'),{earnedCoins:50});
    await setDoc(doc(db,'live_streams/live_rules/join_requests/liveGuest'),{uid:'liveGuest',status:'pending'});
    await setDoc(doc(db,'live_streams/live_rules/gifts/receipt'),{senderUid:'liveViewer',recipientUid:'liveGuest',coins:50});
    await setDoc(doc(db,'live_pk_deadlines/live_rules'),{pkId:'pk',endsAtMs:1000});
  });
  const host=env.authenticatedContext('liveHost').firestore(),guest=env.authenticatedContext('liveGuest').firestore();
  const viewer=env.authenticatedContext('liveViewer').firestore(),outsider=env.authenticatedContext('liveOutsider').firestore();
  const anonymous=env.unauthenticatedContext().firestore();
  await assertSucceeds(getDoc(doc(viewer,'wallets/liveViewer')));
  await assertFails(getDoc(doc(guest,'wallets/liveViewer')));
  await assertFails(getDoc(doc(anonymous,'wallets/liveViewer')));
  await assertFails(setDoc(doc(viewer,'wallets/liveViewer'),{coins:99999}));
  await assertFails(updateDoc(doc(guest,'wallets/liveGuest'),{earnedCoins:99999}));
  await assertFails(deleteDoc(doc(viewer,'wallets/liveViewer')));
  await assertFails(setDoc(doc(outsider,'wallets/liveOutsider'),{coins:500}));
  await assertSucceeds(getDoc(doc(anonymous,'live_streams/live_rules')));
  await assertFails(setDoc(doc(host,'live_streams/fake_live'),{ownerId:'liveHost',active:true}));
  await assertFails(updateDoc(doc(host,'live_streams/live_rules'),{'pk.hostScore':999,guestUid:'liveOutsider'}));
  await assertFails(deleteDoc(doc(host,'live_streams/live_rules')));
  await assertSucceeds(getDoc(doc(guest,'live_streams/live_rules/join_requests/liveGuest')));
  await assertSucceeds(getDocs(collection(host,'live_streams/live_rules/join_requests')));
  await assertFails(getDoc(doc(outsider,'live_streams/live_rules/join_requests/liveGuest')));
  await assertFails(getDocs(collection(outsider,'live_streams/live_rules/join_requests')));
  await assertFails(setDoc(doc(viewer,'live_streams/live_rules/join_requests/liveViewer'),{uid:'liveViewer',status:'accepted'}));
  await assertFails(updateDoc(doc(host,'live_streams/live_rules/join_requests/liveGuest'),{status:'accepted'}));
  await assertSucceeds(getDoc(doc(viewer,'live_streams/live_rules/gifts/receipt')));
  await assertFails(getDoc(doc(anonymous,'live_streams/live_rules/gifts/receipt')));
  await assertFails(setDoc(doc(viewer,'live_streams/live_rules/gifts/forged'),{coins:500,recipientUid:'liveHost'}));
  await assertFails(updateDoc(doc(host,'live_streams/live_rules/gifts/receipt'),{coins:1000}));
  await assertFails(deleteDoc(doc(viewer,'live_streams/live_rules/gifts/receipt')));
  await assertFails(getDoc(doc(viewer,'live_pk_deadlines/live_rules')));
  await assertFails(setDoc(doc(host,'live_pk_deadlines/fake'),{pkId:'fake',endsAtMs:0}));
  const comment=()=>({userId:'liveViewer',uid:'liveViewer',username:'viewer',text:'Merhaba',createdAt:serverTimestamp()});
  await assertSucceeds(setDoc(doc(viewer,'live_streams/live_rules/comments/valid'),comment()));
  await assertFails(setDoc(doc(viewer,'live_streams/live_rules/comments/spoof_user'),{...comment(),userId:'liveHost'}));
  await assertFails(setDoc(doc(viewer,'live_streams/live_rules/comments/spoof_uid'),{...comment(),uid:'liveHost'}));
  await assertFails(setDoc(doc(viewer,'live_streams/live_rules/comments/too_long'),{...comment(),text:'x'.repeat(501)}));
  await assertFails(setDoc(doc(viewer,'live_streams/live_rules/comments/empty'),{...comment(),text:''}));
  await assertFails(setDoc(doc(viewer,'live_streams/live_closed/comments/closed'),comment()));
  await assertFails(updateDoc(doc(viewer,'live_streams/live_rules/comments/valid'),{userId:'liveHost'}));
  await assertSucceeds(updateDoc(doc(viewer,'live_streams/live_rules/comments/valid'),{text:'Düzenlendi',editedAt:serverTimestamp()}));
  await assertFails(deleteDoc(doc(outsider,'live_streams/live_rules/comments/valid')));
  await assertSucceeds(deleteDoc(doc(viewer,'live_streams/live_rules/comments/valid')));
  const reaction=()=>({uid:'liveViewer',type:'heart',createdAt:serverTimestamp()});
  await assertSucceeds(setDoc(doc(viewer,'live_streams/live_rules/reactions/liveViewer'),reaction()));
  await assertFails(setDoc(doc(viewer,'live_streams/live_rules/reactions/liveHost'),{...reaction(),uid:'liveHost'}));
  await assertFails(setDoc(doc(viewer,'live_streams/live_closed/reactions/liveViewer'),reaction()));
  await assertFails(updateDoc(doc(viewer,'live_streams/live_rules/reactions/liveViewer'),{type:'coins'}));
  await assertSucceeds(deleteDoc(doc(viewer,'live_streams/live_rules/reactions/liveViewer')));
  console.log('Canlı yayın/cüzdan/hediye/katılım/yorum/tepki Firestore kuralları emülatör testleri geçti.');
}
