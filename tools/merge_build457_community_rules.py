"""Replace only the generated Build450-457 community rule namespace.

Never replace the entire Firestore rules file: unrelated group/chat/privacy
rules are generated by later build scripts and must remain byte-for-byte
unchanged. The merge fails closed when source anchors are unfamiliar.
"""

LEGACY_FIRST = "    function communitySigned450() {"
HARDENED_FIRST = "    function community450(cid) {"
LAST = "    match /communityInvites450/{code} {"


def section_end(text: str, marker: str) -> int:
    if text.count(marker) != 1:
        raise ValueError(f"Expected exactly one rule marker: {marker}")
    opening=text.index(marker)+len(marker)-1
    if text[opening]!='{':
        raise ValueError(f"Invalid rule scope opening: {marker}")
    level=0
    for i in range(opening,len(text)):
        if text[i]=='{':
            level+=1
        elif text[i]=='}':
            level-=1
            if level==0:
                return i+1
            if level<0:
                break
    raise ValueError(f"Unclosed Firestore rule scope: {marker}")


def merge_hardened_community(generated: str, hardened: str) -> str:
    for text in (generated,hardened):
        if text.count("match /communities450/{cid} {")!=1:
            raise ValueError("Exactly one community namespace is required")
        if text.count(LAST)!=1:
            raise ValueError("Exactly one community invites namespace is required")
    if generated.count(LEGACY_FIRST)!=1 or hardened.count(HARDENED_FIRST)!=1:
        raise ValueError("Expected old and proposed community marker not found")
    g_start=generated.index(LEGACY_FIRST)
    g_end=section_end(generated,LAST)
    h_start=hardened.index(HARDENED_FIRST)
    h_end=section_end(hardened,LAST)
    if g_end<=g_start or h_end<=h_start:
        raise ValueError("Invalid community rule range")
    old_segment=generated[g_start:g_end]
    new_segment=hardened[h_start:h_end]
    if "match /communities450/{cid} {" not in old_segment or (
        "function community450PostView(cid, pid)" not in new_segment
    ):
        raise ValueError("Unexpected incomplete community rule scope")
    merged=generated[:g_start]+new_segment+generated[g_end:]
    if merged.count("match /communities450/{cid} {")!=1 or merged.count(LAST)!=1:
        raise ValueError("Duplicate community matches after merge")
    if merged[:g_start]!=generated[:g_start] or (
        merged[g_start+len(new_segment):]!=generated[g_end:]
    ):
        raise ValueError("Noncommunity rules changed unexpectedly")
    return merged
